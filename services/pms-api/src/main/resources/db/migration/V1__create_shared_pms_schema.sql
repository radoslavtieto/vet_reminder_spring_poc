CREATE TABLE invoice (
    id BIGINT NOT NULL AUTO_INCREMENT,
    tenant_id CHAR(2) NOT NULL,
    public_id CHAR(36) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    version BIGINT NOT NULL DEFAULT 0,
    deleted_at TIMESTAMP(6) NULL,
    clinic_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    visit_id BIGINT NULL,
    invoice_no VARCHAR(60) NOT NULL,
    status VARCHAR(20) NOT NULL,
    issued_on DATE NOT NULL,
    due_on DATE NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'EUR',
    total_amount DECIMAL(12,2) NOT NULL,
    paid_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uq_invoice_tenant_public_id (tenant_id, public_id),
    UNIQUE KEY uq_invoice_tenant_id (tenant_id, id),
    UNIQUE KEY uq_invoice_tenant_clinic_invoice_no (tenant_id, clinic_id, invoice_no),
    KEY idx_invoice_tenant_client (tenant_id, client_id),
    KEY idx_invoice_tenant_visit (tenant_id, visit_id),
    KEY idx_invoice_tenant_status_due (tenant_id, status, due_on),
    KEY idx_invoice_tenant_deleted (tenant_id, deleted_at),
    CONSTRAINT chk_invoice_status CHECK (status IN ('DRAFT', 'ISSUED', 'PARTIALLY_PAID', 'PAID', 'VOID')),
    CONSTRAINT chk_invoice_amounts CHECK (total_amount >= 0 AND paid_amount >= 0),
    CONSTRAINT fk_invoice_clinic FOREIGN KEY (tenant_id, clinic_id) REFERENCES clinic (tenant_id, id),
    CONSTRAINT fk_invoice_client FOREIGN KEY (tenant_id, client_id) REFERENCES client (tenant_id, id),
    CONSTRAINT fk_invoice_visit FOREIGN KEY (tenant_id, visit_id) REFERENCES visit (tenant_id, id)
) ENGINE=InnoDB;

